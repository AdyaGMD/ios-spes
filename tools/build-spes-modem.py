#!/usr/bin/env python3
"""Build SpesModem.cpp from TopazModem.cpp with verified spes modem_a tables.
"""
import json
import re

def main():
    with open("research/spes-modem-map.json", "r") as f:
        map_data = json.load(f)

    files = map_data["files"]

    # 1. Generate fw_files
    modem_files = []
    for path, info in sorted(files.items()):
        name = path.replace("image/", "")
        if name.startswith("modem.b") or name == "modem.mdt":
            ext = info["extents"][0]
            modem_files.append((name, ext["offset"], info["size"], info["crc32"]))

    fw_files_code = "static const struct { const char *name; uint32_t off, size, crc; } fw_files[] = {\n"
    for name, off, size, crc in modem_files:
        fw_files_code += f'\t{{ "{name}", 0x{off:x}, 0x{size:x}, 0x{crc} }},\n'
    fw_files_code += "};\n"

    # 2. Generate fw_ext and fw_all
    ext_list = []
    file_list = []
    for path, info in sorted(files.items()):
        ext_idx = len(ext_list)
        ext_count = len(info["extents"])
        for ext in info["extents"]:
            ext_list.append((ext["offset"], ext["length"]))
        file_list.append((path, info["size"], ext_idx, ext_count))

    fw_ext_code = f"/* generated from spes-modem-map.json: {len(file_list)} files, {len(ext_list)} extents */\n"
    fw_ext_code += f"static const struct {{ uint32_t off, len; }} fw_ext[] = {{\n"
    for off, length in ext_list:
        fw_ext_code += f"\t{{ 0x{off:x}, 0x{length:x} }},\n"
    fw_ext_code += "};\n"

    fw_ext_code += f"static const struct {{ const char *path; uint32_t size; uint16_t ext, next; }} fw_all[] = {{\n"
    for path, size, ext_idx, ext_count in file_list:
        fw_ext_code += f'\t{{ "{path}", 0x{size:x}, {ext_idx}, {ext_count} }},\n'
    fw_ext_code += "};\n\n"

    # 3. Read TopazModem.cpp
    with open("research/upstream-wifi/tree/iokit/Kernel/arm/TopazModem.cpp", "r") as f:
        src = f.read()

    # Replace fw_files[]
    fw_files_pattern = re.compile(r"static const struct \{ const char \*name; uint32_t off, size, crc; \} fw_files\[\] = \{.*?\};\n", re.DOTALL)
    assert fw_files_pattern.search(src), "fw_files pattern not found"
    src = fw_files_pattern.sub(fw_files_code, src, count=1)

    # Replace fw_ext and fw_all using substring boundaries
    start_tag = "/* generated by fwtable_all.py"
    end_tag = "static int\nfw_all_find"
    idx1 = src.find(start_tag)
    idx2 = src.find(end_tag)
    assert idx1 != -1 and idx2 != -1, f"tags not found: {idx1}, {idx2}"
    src = src[:idx1] + fw_ext_code + src[idx2:]

    # Replace TopazModem with SpesModem in logs and comments
    src = src.replace('IOLog("TopazModem: ', 'IOLog("SpesModem: ')
    src = src.replace("topaz_modem_init", "spes_modem_init")
    src = src.replace("topaz_modem_thread", "spes_modem_thread")
    src = src.replace("topaz_wlan_", "spes_wlan_")

    # Add backwards-compatibility aliases for topaz_wlan_* and topaz_modem_init
    aliases = """
/* Topaz compatibility aliases */
extern "C" {
void topaz_modem_init(void) { spes_modem_init(); }
bool topaz_wlan_ready(void) { return spes_wlan_ready(); }
int topaz_wlan_scan(void) { return spes_wlan_scan(); }
bool topaz_wlan_heard(unsigned i, struct spes_wlan_bss *b) { return spes_wlan_heard(i, (struct spes_wlan_bss *)b); }
void topaz_wlan_address(uint8_t a[6]) { spes_wlan_address(a); }
int topaz_wlan_join(const uint8_t *s, unsigned sl, const uint8_t *b, const uint8_t *p, unsigned pl) { return spes_wlan_join(s, sl, b, p, pl); }
int topaz_wlan_join_pmk(const uint8_t *s, unsigned sl, const uint8_t *b, const uint8_t pmk[32]) { return spes_wlan_join_pmk(s, sl, b, pmk); }
int topaz_wlan_leave(void) { return spes_wlan_leave(); }
bool topaz_wlan_joined(void) { return spes_wlan_joined(); }
bool topaz_wlan_transmit(const uint8_t *f, size_t l) { return spes_wlan_transmit(f, l); }
}
"""
    # Insert aliases before final #else
    src = src.replace("#else\nextern \"C\" void spes_modem_init(void) {}", aliases + "\n#else\nextern \"C\" void spes_modem_init(void) {}\nextern \"C\" void topaz_modem_init(void) {}\n")

    out_file = "research/xnu-check/iokit/Kernel/arm/SpesModem.cpp"
    with open(out_file, "w") as f:
        f.write(src)

    print(f"Wrote {out_file} ({len(src.splitlines())} lines)")

if __name__ == "__main__":
    main()
