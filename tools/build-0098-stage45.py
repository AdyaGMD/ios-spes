def odd_bit(val):
    p = 1
    while val:
        p ^= 1
        val &= val - 1
    return p

def pm4_type7(opcode, count):
    return 0x70000000 | count | (odd_bit(count) << 15) | (opcode << 16) | (odd_bit(opcode) << 23)

def pm4_type4(reg, count):
    return 0x40000000 | count | (odd_bit(count) << 7) | (reg << 8) | (odd_bit(reg) << 27)

