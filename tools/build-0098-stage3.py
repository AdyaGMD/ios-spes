#!/usr/bin/env python3
"""Build and verify xnu/patches/0098-spes-glink-rpm-transport.patch with GPU Stage 3.
"""
import struct
import tempfile
import subprocess
from pathlib import Path

def main():
    root = Path("/Users/adya/Documents/iospes")
    xnu_check = root / "research" / "xnu-check"
    touch_base = (xnu_check / "bsd/dev/sweet_touch.c.0097").read_text()

    # 1. Generate sweet_sqe.h content
    sqe_path = root / "research" / "spes-gpu-firmware" / "a630_sqe.fw"
    sqe_bytes = sqe_path.read_bytes()[4:] # Skip 4 bytes header
    words = struct.unpack(f"<{len(sqe_bytes)//4}I", sqe_bytes)
    assert len(words) == 8065

    sqe_lines = [
        "/* Autogenerated A630 SQE microcode for Adreno 610 */",
        "#ifndef _SWEET_SQE_H_",
        "#define _SWEET_SQE_H_",
        f"static const uint32_t a630_sqe_fw[{len(words)}] = {{",
    ]
    for i in range(0, len(words), 8):
        chunk = words[i:i+8]
        hex_str = ", ".join(f"0x{w:08x}u" for w in chunk)
        sqe_lines.append(f"\t{hex_str},")
    sqe_lines.append("};")
    sqe_lines.append("#endif /* _SWEET_SQE_H_ */\n")
    sweet_sqe_content = "\n".join(sqe_lines)

    # 2. Update sweet_touch.c
    touch_curr = (xnu_check / "bsd/dev/sweet_touch.c").read_text()

    includes_old = """#include <pexpert/pexpert.h>
#include <pexpert/device_tree.h>"""

    includes_new = """#include <pexpert/pexpert.h>
#include <pexpert/device_tree.h>
#include <arm/caches_internal.h>
#include <vm/pmap.h>
#include <vm/vm_kern.h>
#include "sweet_sqe.h"

extern ppnum_t pmap_find_phys(pmap_t pmap, addr64_t va);"""

    assert includes_old in touch_curr, "Includes block not found in sweet_touch.c"
    touch_mod = touch_curr.replace(includes_old, includes_new)

    smc_helpers = """static uint64_t
spes_smc(uint64_t a[8])
{
	register uint64_t x0 __asm__("x0") = a[0], x1 __asm__("x1") = a[1], x2 __asm__("x2") = a[2],
	    x3 __asm__("x3") = a[3], x4 __asm__("x4") = a[4], x5 __asm__("x5") = a[5], x6 __asm__("x6") = a[6],
	    x7 __asm__("x7") = a[7];
	__asm__ volatile ("smc #0"
            : "+r"(x0), "+r"(x1), "+r"(x2), "+r"(x3), "+r"(x4), "+r"(x5), "+r"(x6), "+r"(x7)
            :
            : "x8", "x9", "x10", "x11", "x12", "x13", "x14", "x15", "x16", "x17", "memory");
	a[0] = x0; a[1] = x1; a[2] = x2; a[3] = x3; a[4] = x4; a[5] = x5; a[6] = x6; a[7] = x7;
	return x0;
}

static uint64_t
spes_scm(uint32_t fn, uint64_t arginfo, uint64_t a, uint64_t b, uint64_t c, uint64_t *res1)
{
	uint64_t args[8] = { fn, arginfo, a, b, c, 0, 0, 0 };
	spes_smc(args);
	for (unsigned n = 0; args[0] == 1 && n < 100000; n++) {
		uint64_t again[8] = { 1, arginfo, a, b, c, 0, args[6], 0 };
		memcpy(args, again, sizeof(args));
		spes_smc(args);
	}
	if (res1 != NULL) {
		*res1 = args[1];
	}
	return args[0];
}
"""
    assert "static void\nspes_glink_rpm_probe(void)" in touch_mod
    touch_mod = touch_mod.replace("static void\nspes_glink_rpm_probe(void)", smc_helpers + "\nstatic void\nspes_glink_rpm_probe(void)")

    stage2_target = """\tprintf("SPES GPU: 22. GPU STAGE-2 COMPLETE!\\n");
}"""

    stage3_code = """\tprintf("SPES GPU: 22. GPU STAGE-2 COMPLETE!\\n");

	/* ================================================================
	 * STAGE 3: SMMUv2, TrustZone PAS 13, SQE Microcode, Ringbuffer NOP
	 * ================================================================ */
	printf("SPES GPU: starting Stage 3 bringup...\\n");

	/* Step 13: Map GPU SMMU MMIO aperture (0x059a0000, 64 KiB) */
	vm_offset_t smmu = ml_io_map(0x059a0000u, 0x10000u);
	if (!smmu) {
		printf("SPES GPU: SMMU MMIO map failed\\n");
		return;
	}
	uint32_t smmu_scr0 = touch_rd(smmu, 0x00u);
	uint32_t smmu_id0  = touch_rd(smmu, 0x20u);
	uint32_t smmu_id1  = touch_rd(smmu, 0x24u);
	uint32_t smmu_id2  = touch_rd(smmu, 0x28u);

	uint32_t shift = (smmu_id1 >> 31) ? 16 : 12;
	uint32_t pages = 1u << (((smmu_id1 >> 28) & 7u) + 1u);
	uint32_t stride = 1u << shift;
	uint32_t num_cb = smmu_id1 & 0xffu;
	uint32_t cb0_off = pages * stride;

	printf("SPES GPU: 23. SMMU sCR0=%#x ID0=%#x ID1=%#x (pgsz=%uK pages=%u cb=%u)\\n",
	    smmu_scr0, smmu_id0, smmu_id1, (1u << (shift - 10)), pages, num_cb);

	uint32_t cb0_sctlr = touch_rd(smmu, cb0_off);
	uint32_t cb0_fsr   = touch_rd(smmu, cb0_off + 0x58u);
	uint32_t cbar0     = touch_rd(smmu, stride + 0x00u);
	uint32_t cba2r0    = touch_rd(smmu, stride + 0x800u);
	printf("SPES GPU: 23b. CB0 SCTLR=%#x FSR=%#x CBAR0=%#x CBA2R0=%#x\\n",
	    cb0_sctlr, cb0_fsr, cbar0, cba2r0);

	/* Ensure bypass mode on CB0 (M=0) */
	if (cb0_sctlr & 1u) {
		touch_wr(smmu, cb0_off, 0u);
		__asm__ volatile ("dsb sy" ::: "memory");
		printf("SPES GPU: 23c. CB0 SCTLR forced to bypass: %#x\\n", touch_rd(smmu, cb0_off));
	}

	/* Step 14: Query TrustZone for PAS ID 13 (ZAP shader) support */
	uint64_t tz_res = 0;
	uint64_t tz_st = spes_scm(0x42000000u | (0x02u << 8) | 0x07u, 1, 13, 0, 0, &tz_res);
	printf("SPES GPU: 24. TrustZone PAS 13 check: st=%#llx res=%#llx\\n", tz_st, tz_res);

	/* Step 15: Allocate physically contiguous DMA memory for SQE microcode */
	vm_offset_t sqe_va = 0;
	if (kmem_alloc_contig(kernel_map, &sqe_va, 32768, PAGE_MASK, 0, 0,
	    KMA_DATA | KMA_ZERO | KMA_PERMANENT, VM_KERN_MEMORY_IOKIT) != KERN_SUCCESS) {
		printf("SPES GPU: kmem_alloc_contig for SQE microcode failed\\n");
		return;
	}
	ppnum_t sqe_pn = pmap_find_phys(kernel_pmap, (addr64_t)sqe_va);
	uint64_t sqe_pa = ptoa_64(sqe_pn);

	/* Copy A630 SQE device code (32,260 bytes, 8065 words) */
	memcpy((void *)sqe_va, a630_sqe_fw, sizeof(a630_sqe_fw));
	clean_dcache64(sqe_pa, sizeof(a630_sqe_fw), TRUE);
	__asm__ volatile ("dsb sy" ::: "memory");
	printf("SPES GPU: 25. SQE ucode (%lu bytes) at pa=%#llx va=%#lx\\n",
	    sizeof(a630_sqe_fw), sqe_pa, (unsigned long)sqe_va);

	/* Step 16: Program CP SQE Base Registers (dword 0x0830 -> 0x20c0) */
	touch_wr(gpu, 0x20c0u, (uint32_t)sqe_pa);
	touch_wr(gpu, 0x20c4u, (uint32_t)(sqe_pa >> 32));
	__asm__ volatile ("dsb sy" ::: "memory");
	uint32_t base_lo = touch_rd(gpu, 0x20c0u);
	uint32_t base_hi = touch_rd(gpu, 0x20c4u);
	printf("SPES GPU: 25b. CP_SQE_INSTR_BASE=%#x:%#x (match=%d)\\n",
	    base_hi, base_lo, (base_lo == (uint32_t)sqe_pa && base_hi == (uint32_t)(sqe_pa >> 32)));

	/* Step 17: Allocate Ringbuffer (8 KiB) + Fence (8 KiB) */
	vm_offset_t rb_va = 0;
	if (kmem_alloc_contig(kernel_map, &rb_va, 16384, PAGE_MASK, 0, 0,
	    KMA_DATA | KMA_ZERO | KMA_PERMANENT, VM_KERN_MEMORY_IOKIT) != KERN_SUCCESS) {
		printf("SPES GPU: kmem_alloc_contig for Ringbuffer failed\\n");
		return;
	}
	ppnum_t rb_pn = pmap_find_phys(kernel_pmap, (addr64_t)rb_va);
	uint64_t rb_pa = ptoa_64(rb_pn);
	uint64_t fence_pa = rb_pa + 8192u;
	volatile uint32_t *rb = (volatile uint32_t *)rb_va;

	bzero((void *)rb_va, 16384);
	clean_dcache64(rb_pa, 16384, TRUE);
	__asm__ volatile ("dsb sy" ::: "memory");

	/* Program Ringbuffer registers */
	touch_wr(gpu, 0x2000u, (uint32_t)rb_pa);           /* CP_RB_BASE_LO */
	touch_wr(gpu, 0x2004u, (uint32_t)(rb_pa >> 32));  /* CP_RB_BASE_HI */
	touch_wr(gpu, 0x2008u, 0x020au);                  /* CP_RB_CNTL (8K ring, 32B block) */
	touch_wr(gpu, 0x2010u, (uint32_t)fence_pa);       /* CP_RB_RPTR_ADDR_LO */
	touch_wr(gpu, 0x2014u, (uint32_t)(fence_pa >> 32));/* CP_RB_RPTR_ADDR_HI */
	touch_wr(gpu, 0x2018u, 0u);                       /* CP_RB_RPTR */
	touch_wr(gpu, 0x201cu, 0u);                       /* CP_RB_WPTR */
	touch_wr(gpu, 0x2214u, 0u);                       /* CP_SCRATCH(2) */
	__asm__ volatile ("dsb sy" ::: "memory");

	/* Step 18: Un-halt CP SQE engine */
	touch_wr(gpu, 0x2020u, 1u); /* CP_SQE_CNTL = 1 */
	touch_wait(10);

	uint32_t cp_hw_fault = touch_rd(gpu, 0x2084u);
	uint32_t cp_int_stat = touch_rd(gpu, 0x208cu);
	touch_wr(gpu, 0x2094u, 1u); /* CP_SQE_STAT_ADDR = 1 */
	uint32_t sqe_stat = touch_rd(gpu, 0x2098u); /* CP_SQE_STAT_DATA */
	uint32_t curr_rptr = touch_rd(gpu, 0x2018u);
	uint32_t curr_wptr = touch_rd(gpu, 0x201cu);
	rbbm_status = touch_rd(gpu, 0x840u);
	printf("SPES GPU: 26. CP started! fault=%#x int=%#x sqe_stat=%#x rptr=%u wptr=%u rbbm=%#x\\n",
	    cp_hw_fault, cp_int_stat, sqe_stat, curr_rptr, curr_wptr, rbbm_status);

	/* Step 19: Submit PM4 NOP packet to ringbuffer and verify silicon execution */
	rb[0] = 0x70100001u; /* Type 7 CP_NOP, 1 payload word */
	rb[1] = 0xca11ab1eu; /* payload marker: 0xCA11AB1E */
	clean_dcache64(rb_pa, 16, TRUE);
	__asm__ volatile ("dsb sy" ::: "memory");

	/* Advance WPTR to 2 words */
	touch_wr(gpu, 0x201cu, 2u);
	touch_wait(5);

	bool consumed = false;
	int poll_i = 0;
	for (poll_i = 0; poll_i < 200; ++poll_i) {
		curr_rptr = touch_rd(gpu, 0x2018u);
		if (curr_rptr == 2u) {
			consumed = true;
			break;
		}
		touch_wait(1);
	}
	printf("SPES GPU: 27. RING NOP EXECUTION: rptr=%u / wptr=2 (consumed=%d poll=%d)\\n",
	    curr_rptr, consumed, poll_i);
	printf("SPES GPU: 27b. RBBM_STATUS=%#x CP_HW_FAULT=%#x CP_INT=%#x\\n",
	    touch_rd(gpu, 0x840u), touch_rd(gpu, 0x2084u), touch_rd(gpu, 0x208cu));
	printf("SPES GPU: 28. GPU STAGE-3 COMPLETE!\\n");
}"""

    assert stage2_target in touch_mod, "Stage 2 complete target not found in sweet_touch.c"
    touch_mod = touch_mod.replace(stage2_target, stage3_code)

    # 3. Create temporary git repository and verify patch generation
    with tempfile.TemporaryDirectory() as td:
        tpath = Path(td)
        subprocess.run(["git", "init"], cwd=tpath, check=True, capture_output=True)
        subprocess.run(["git", "config", "user.name", "test"], cwd=tpath, check=True)
        subprocess.run(["git", "config", "user.email", "test@test.com"], cwd=tpath, check=True)

        (tpath / "bsd/dev").mkdir(parents=True)
        (tpath / "bsd/dev/sweet_touch.c").write_text(touch_base)
        subprocess.run(["git", "add", "."], cwd=tpath, check=True)
        subprocess.run(["git", "commit", "-m", "base-0097"], cwd=tpath, check=True, capture_output=True)

        # Apply modified files
        (tpath / "bsd/dev/sweet_touch.c").write_text(touch_mod)
        (tpath / "bsd/dev/sweet_sqe.h").write_text(sweet_sqe_content)

        subprocess.run(["git", "add", "-N", "bsd/dev/sweet_sqe.h"], cwd=tpath, check=True)
        diff_res = subprocess.run(["git", "diff"], cwd=tpath, check=True, capture_output=True, text=True)

        # Test apply check on clean base
        subprocess.run(["git", "checkout", "."], cwd=tpath, check=True, capture_output=True)
        subprocess.run(["rm", "-f", "bsd/dev/sweet_sqe.h"], cwd=tpath, check=True)

        apply_res = subprocess.run(["git", "apply", "--check"], input=diff_res.stdout, cwd=tpath, capture_output=True, text=True)
        assert apply_res.returncode == 0, f"git apply --check failed:\n{apply_res.stderr}"

        # Save to xnu-check and patch file
        (xnu_check / "bsd/dev/sweet_touch.c").write_text(touch_mod)
        (xnu_check / "bsd/dev/sweet_sqe.h").write_text(sweet_sqe_content)

        out_patch = root / "xnu" / "patches" / "0098-spes-glink-rpm-transport.patch"
        out_patch.write_text(diff_res.stdout)
        print(f"SUCCESS: Generated {out_patch} ({len(diff_res.stdout.splitlines())} lines, {len(diff_res.stdout)} bytes)")

if __name__ == "__main__":
    main()
